#!/usr/bin/env python3
"""Make the MapKit JS token the city guide maps use, and write it into stamped-cities/map-token.js.

    python3 tools/stamped/make_mapkit_token.py                      # site token, valid 1 year
    python3 tools/stamped/make_mapkit_token.py --origin http://localhost:8765 --days 1   # local testing

The token is public by design: it sits in the page, and Apple only honors it on the
origin(s) baked into it. The private key (~/.mapkit/AuthKey_<KEY_ID>.p8) never leaves
this computer. Re-run before the token expires; the expiry date is printed and also
written into map-token.js. Needs PyJWT with crypto support: pip install "pyjwt[crypto]".
"""
import argparse
import time
from datetime import datetime, timezone
from pathlib import Path

import jwt

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "stamped-cities" / "map-token.js"
TEAM_ID = "S4RSN4KFD3"
KEY_ID = "HWLV7JPK43"
KEY_FILE = Path.home() / ".mapkit" / f"AuthKey_{KEY_ID}.p8"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--origin", default="https://georgeclinkscalesdev.com")
    parser.add_argument("--days", type=int, default=365)
    args = parser.parse_args()

    now = int(time.time())
    expires = now + args.days * 86400
    token = jwt.encode(
        {"iss": TEAM_ID, "iat": now, "exp": expires, "origin": args.origin},
        KEY_FILE.read_text(),
        algorithm="ES256",
        headers={"kid": KEY_ID, "typ": "JWT"},
    )
    expiry = datetime.fromtimestamp(expires, timezone.utc).strftime("%Y-%m-%d")
    OUT.write_text(
        "// MapKit JS token for the city guide maps. Generated by tools/stamped/make_mapkit_token.py.\n"
        f"// Only works on {args.origin}. Expires {expiry}; re-run the script before then.\n"
        f'window.STAMPED_MAPKIT_TOKEN = "{token}";\n',
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)} for {args.origin}, expires {expiry}")


if __name__ == "__main__":
    main()
